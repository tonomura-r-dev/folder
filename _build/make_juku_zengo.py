def text_span(dark, x, y):
    """(x, y) の近くの文字の範囲（x0, x1, 文字の高さ）。見つからなければ None"""
    import numpy as np
    H, W = dark.shape
    best = None
    for yy in range(y - 10, y + 11, 2):
        band = dark[max(yy - 12, 0):yy + 13].sum(axis=0)
        xs = [c for c in range(max(x - 12, 0), min(x + 30, W)) if band[c] > 0]
        if not xs:
            continue
        x0 = xs[0]
        gap = 0
        while x0 > 0 and gap <= 10:
            x0 -= 1
            gap = gap + 1 if band[x0] == 0 else 0
        x0 += gap
        x1, gap = xs[-1], 0
        while x1 < W - 1 and gap <= 18 and x1 - x0 < 330:
            x1 += 1
            gap = gap + 1 if band[x1] == 0 else 0
        x1 -= gap
        rows = np.nonzero(dark[max(yy - 12, 0):yy + 13, x0:x1 + 1].sum(axis=1))[0]
        if len(rows) == 0:
            continue
        cy = max(yy - 12, 0) + (rows.min() + rows.max()) // 2
        score = abs(cy - y)
        if best is None or score < best[0]:
            best = (score, x0, x1, cy)
    return None if best is None else best[1:]


def norm(t):
    for a, b in FIX:
        t = t.replace(a, b)
    return t


def classify(label):
    t = norm(label)
    if len(re.sub(r"[^\w]", "", t)) < 2:
        return None
    for cat, pat in RULES:
        if re.search(pat, t):
            return cat
    return None


def render(key):
    src = Image.open(SRC_DIR / f"{key}_塾.webp").convert("RGB")
    rows = list(csv.DictReader(open(ROOT / f"_data/zengo/塾_{key}_塾_OCR.csv", encoding="utf-8")))
    base = Image.blend(src, Image.new("RGB", src.size, "white"), 0.55)   # 分類外は控えめに
    over = Image.new("RGBA", src.size, (0, 0, 0, 0))
    od = ImageDraw.Draw(over)
    import numpy as np
    arr = np.asarray(src).astype(int)
    dark = (arr[..., 0] < 130) & (arr[..., 1] < 130) & (arr[..., 2] < 150)
    for r in rows:
        r["cat"] = classify(r["label"])
    missed = []
    for x, y, cat in OVR.get(key, []):
        hit = [r for r in rows if int(r["x0"]) - 10 <= x <= int(r["x1"]) + 10 and abs(int(r["y"]) - y) <= 14]
        if hit:
            hit.sort(key=lambda r: abs(int(r["y"]) - y))
            for r in rows:   # 同じ文字の重なった候補も、同じ分類に
                if abs(int(r["y"]) - int(hit[0]["y"])) < 12 and min(int(r["x1"]), int(hit[0]["x1"])) - max(int(r["x0"]), int(hit[0]["x0"])) > 0:
                    r["cat"] = cat
            hit[0]["force"] = True
            continue
        sp = text_span(dark, x, y)
        if sp is None:
            missed.append((x, y))
            continue
        x0, x1, cy = sp
        rows.append(dict(label="", x=str(x0 - 12), y=str(cy), py=str(cy), x0=str(x0), x1=str(x1), cat=cat, force=True, nodot=True))
    if missed:
        print("  見つからなかった直し:", missed)
    boxes, n = [], {c: 0 for c in COL}
    taken = []
    rows.sort(key=lambda r: (not r.get("force"), abs(int(r["y"]) - int(r["py"]))))   # 直した所、点の高さの文字を優先
    for r in rows:
        cat = r["cat"]
        if cat is None:
            continue
        x, y, py, x0, x1 = (int(r[k]) for k in ("x", "y", "py", "x0", "x1"))
        box = (x0 - 5, y - 15, x1 + 5, y + 15)
        if any(abs(y - ty) < 12 and min(x1, tx1) - max(x0, tx0) > 0.5 * (x1 - x0) for ty, tx0, tx1 in taken):
            continue                                                  # 同じ文字を2回拾ったもの
        taken.append((y, x0, x1))
        boxes.append((box, COL[cat], None if r.get("nodot") else (x, py)))
        od.rounded_rectangle(box, radius=6, fill=COL[cat] + (75,))
        n[cat] += 1
    img = Image.alpha_composite(base.convert("RGBA"), over)
    d = ImageDraw.Draw(img)
    for box, c, dot in boxes:
        # ラベル文字は原画から濃く戻す
        crop = src.crop(box).convert("L")
        mask = crop.point(lambda v: 255 if v < 150 else 0)
        img.paste((40, 40, 40, 255), box, mask)
        if dot:
            x, y = dot
            d.ellipse((x - 9, y - 9, x + 9, y + 9), fill=c + (255,), outline=(255, 255, 255, 255), width=2)
    # 色を付けなかったラベルの文字も、読める濃さに戻す（薄すぎないように）
    out = ROOT / f"_images/juku_zengo_{key}.png"
    img.convert("RGB").save(out)
    return out, n



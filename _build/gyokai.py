COMPILED = [(name, re.compile(pat)) for name, pat in RULES]


def guess(company):
    """社名から業界を返す。判定できなければ空文字。"""
    s = str(company or "").strip()
    if not s:
        return ""
    for name, pat in COMPILED:
        if pat.search(s):
            return name
    return ""



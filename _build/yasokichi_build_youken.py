def _fmt(run, size=10.5, bold=False, color=None):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    return run


def _p(indent=0.0, before=2, after=2):
    pg = doc.add_paragraph()
    pf = pg.paragraph_format
    pf.space_before = Pt(before); pf.space_after = Pt(after)
    pf.line_spacing = 1.25
    if indent:
        pf.left_indent = Inches(indent)
    return pg


def _shade_p(pg, fill):
    pPr = pg._p.get_or_add_pPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear'); shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), fill)
    pPr.append(shd)


def _shade_c(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear'); shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), fill)
    tcPr.append(shd)


def para(text='', size=10.5, bold=False, color=None, before=2, after=2, indent=0.0):
    pg = _p(indent, before, after)
    if text:
        _fmt(pg.add_run(text), size, bold, color)
    return pg


def h1(num, text):
    pg = _p(0, 16, 7)
    _fmt(pg.add_run('  %s　%s' % (num, text)), 12.5, True, WHITE)
    _shade_p(pg, '1F2A5C')
    return pg


def h2(num, text):
    pg = _p(0, 12, 4)
    _fmt(pg.add_run('%s　%s' % (num, text)), 11.5, True, NAVY)
    return pg


def bullet(text, mark='・', size=10.5, indent=0.14, color=None, bold=False):
    pg = _p(indent, 2, 2)
    _fmt(pg.add_run(mark + text), size, bold, color)
    return pg


def cell_text(cell, text, size=9.5, bold=False, color=None, center=False):
    cell.text = ''
    for i, ln in enumerate(str(text).split('\n')):
        pg = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
        pf = pg.paragraph_format
        pf.space_before = Pt(2); pf.space_after = Pt(2); pf.line_spacing = 1.1
        if center:
            pg.alignment = WD_ALIGN_PARAGRAPH.CENTER
        _fmt(pg.add_run(ln), size, bold, color)


def _tr_flag(row, tag):
    row._tr.get_or_add_trPr().append(OxmlElement('w:' + tag))


def table(headers, rows, weights, highlight=None):
    hl = set(highlight or [])
    total = float(sum(weights))
    widths = [CW * w / total for w in weights]
    tb = doc.add_table(rows=1 + len(rows), cols=len(headers))
    tb.style = 'Table Grid'
    tb.alignment = WD_TABLE_ALIGNMENT.LEFT
    tb.autofit = False
    _tr_flag(tb.rows[0], 'tblHeader')
    for r in tb.rows:
        _tr_flag(r, 'cantSplit')
    for j, h in enumerate(headers):
        c = tb.rows[0].cells[j]
        cell_text(c, h, 9.5, True, WHITE, center=True)
        _shade_c(c, '1F2A5C')
    for i, r in enumerate(rows):
        for j, v in enumerate(r):
            c = tb.rows[i + 1].cells[j]
            on = i in hl
            cell_text(c, v, 9.5, bold=on, color=(ACCENT if on else None))
            _shade_c(c, 'FDF0E6' if on else ('F2F4F8' if i % 2 == 0 else 'FFFFFF'))
    for row in tb.rows:
        for j, w in enumerate(widths):
            row.cells[j].width = Inches(w)
    para('', before=0, after=6)
    return tb



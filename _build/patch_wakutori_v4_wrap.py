def ptext(p):
    return "".join(t.text or "" for t in p.iter(qn("a:t")))


def break_para(p, parts):
    rs = p.findall(qn("a:r"))
    rpr = rs[0].find(qn("a:rPr"))
    for x in rs + p.findall(qn("a:br")):
        p.remove(x)
    end = p.find(qn("a:endParaRPr"))
    for k, part in enumerate(parts):
        if k:
            br = p.makeelement(qn("a:br"), {})
            if rpr is not None:
                br.append(copy.deepcopy(rpr))
            (end.addprevious if end is not None else p.append)(br)
        r = copy.deepcopy(rs[0])
        r.find(qn("a:t")).text = part
        (end.addprevious if end is not None else p.append)(r)


def main(src, out):
    prs = Presentation(src)
    for page, items in BREAKS.items():
        s = prs.slides[page - 1]
        for old, parts in items:
            hit = [p for p in s._element.iter(qn("a:p")) if ptext(p) == old]
            assert len(hit) == 1, (page, old, len(hit))
            break_para(hit[0], parts)
    for sid, lines in DATA24.items():
        set_lines(by_id(prs.slides[23], sid), lines)
    prs.save(out)
    print("saved:", out)



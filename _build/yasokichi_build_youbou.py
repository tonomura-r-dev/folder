def head(ws, row, labels, widths):
    for j, (lb, w) in enumerate(zip(labels, widths), start=1):
        c = ws.cell(row=row, column=j, value=lb)
        c.font = Font(name=FONT, size=10, bold=True, color='FFFFFF')
        c.fill = PatternFill('solid', fgColor=NAVY)
        c.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
        c.border = BORDER
        ws.column_dimensions[chr(64 + j)].width = w
    ws.row_dimensions[row].height = 30


def body(ws, row, values, fill=None, bold_cols=()):
    for j, v in enumerate(values, start=1):
        c = ws.cell(row=row, column=j, value=v)
        c.font = Font(name=FONT, size=10, bold=(j in bold_cols),
                      color=(ACCENT if j in bold_cols else '222222'))
        c.alignment = Alignment(vertical='top', wrap_text=True)
        c.border = BORDER
        if fill:
            c.fill = PatternFill('solid', fgColor=fill)


def title(ws, row, text, size=14):
    c = ws.cell(row=row, column=1, value=text)
    c.font = Font(name=FONT, size=size, bold=True, color=NAVY)
    ws.row_dimensions[row].height = size * 2


def note(ws, row, text, color='55607A'):
    c = ws.cell(row=row, column=1, value=text)
    c.font = Font(name=FONT, size=9.5, color=color)



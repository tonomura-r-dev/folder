# 段落の置き換えのあと、表示しているスライドの文字すべてに当てる（書式はそのまま）
GLOBAL = [
    (re.compile("貴社"), "貴塾"),
    (re.compile("通知メッセ(?!ージ)"), "通知メッセージ"),
    (re.compile("[ヶヵ]月"), "か月"),
    (re.compile("社内想定"), "弊社想定"),
    (re.compile("DYM見解"), "弊社の見解"),
    (re.compile("（仮説）"), ""),
]


def ptext(p):
    out = []
    for ch in p:
        if ch.tag == qn("a:r"):
            out.append(ch.find(qn("a:t")).text or "")
        elif ch.tag == qn("a:br"):
            out.append("\v")
    return "".join(out)


def set_para(p, text):
    runs = p.findall(qn("a:r"))
    for ch in list(p):
        if ch.tag in (qn("a:r"), qn("a:br"), qn("a:fld")) and ch is not runs[0]:
            p.remove(ch)
    runs[0].find(qn("a:t")).text = text


def main(src, out):
    prs = Presentation(src)
    slides = list(prs.slides)
    assert len(slides) == 56
    missing, count = [], 0
    for no, pairs in EDITS.items():
        assert slides[no - 1]._element.get("show") != "0", no
        paras = list(slides[no - 1]._element.iter(qn("a:p")))
        for old, new in pairs:
            hits = [p for p in paras if ptext(p) == old]
            if not hits:
                missing.append((no, old))
            for p in hits:
                set_para(p, new)
                count += 1
    g = 0
    for s in slides:
        if s._element.get("show") == "0":
            continue
        for t in s._element.iter(qn("a:t")):
            if not t.text:
                continue
            new = t.text
            for pat, rep in GLOBAL:
                new = pat.sub(rep, new)
            if new != t.text:
                t.text, g = new, g + 1
    for m in missing:
        print("MISSING", m)
    assert not missing
    prs.save(out)
    print("saved:", out, "paragraphs:", count, "global:", g)



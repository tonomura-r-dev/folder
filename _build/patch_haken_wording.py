def ptext(p):
    out = []
    for ch in p:
        if ch.tag == qn("a:r"):
            out.append(ch.find(qn("a:t")).text or "")
        elif ch.tag == qn("a:br"):
            out.append("\v")
    return "".join(out)


def set_para(p, text):
    runs = p.findall(qn("a:r"))
    for ch in list(p):
        if ch.tag in (qn("a:r"), qn("a:br"), qn("a:fld")) and ch is not runs[0]:
            p.remove(ch)
    runs[0].find(qn("a:t")).text = text


def main(src, out):
    prs = Presentation(src)
    slides = list(prs.slides)
    assert len(slides) == 33
    missing = []
    for no, pairs in EDITS.items():
        paras = list(slides[no - 1]._element.iter(qn("a:p")))
        for old, new in pairs:
            hits = [p for p in paras if ptext(p) == old]
            if not hits:
                missing.append((no, old))
            for p in hits:
                set_para(p, new)
    assert not missing, missing
    # 「プロフィール・リッチメニュー」が1行に収まるよう、その枠だけ左右に少し広げる（中心は動かさない）
    for sh in slides[15].shapes:
        if sh.has_text_frame and any(ptext(p._p) == "◯プロフィール・リッチメニュー" for p in sh.text_frame.paragraphs):
            grow = Emu(Pt(40))
            sh.left, sh.width = sh.left - grow // 2, sh.width + grow
    prs.save(out)
    print("saved:", out, "edits:", sum(len(v) for v in EDITS.values()))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
